#!/usr/bin/env python3
"""Generate src/site/wordmark.generated.ts: the header wordmark as SVG outlines.

The wordmark is drawn in M PLUS Rounded 1c ExtraBold, as on the cover of the
introduction slide. Pages cannot load web fonts (their CSP has no font-src), so
the glyphs are outlined once here instead.

Usage: generate-wordmark.py LATIN.woff2 GREEK.woff2 > src/site/wordmark.generated.ts
The two files are the latin and greek subsets of M PLUS Rounded 1c at weight 800
from Google Fonts (SIL Open Font License 1.1):
  https://fonts.gstatic.com/s/mplusrounded1c/v22/VdGBAYIAV6gnpUpoWwNkYvrugw9RuM0m4qsNz-uEzRRL.woff2 (latin)
  https://fonts.gstatic.com/s/mplusrounded1c/v22/VdGBAYIAV6gnpUpoWwNkYvrugw9RuM0m4qsOz-uEzRRLclI.woff2 (greek)
"""
import sys
from fontTools.ttLib import TTFont
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen

latin, greek = TTFont(sys.argv[1]), TTFont(sys.argv[2])
UPM = latin['head'].unitsPerEm
ASC, DESC = 880, 220  # Room for the ascenders of l/d and the descender of y.
DOT = 0.2 * UPM  # The cover's dot: a 0.2em rounded square.
DOT_MARGIN = 0.04 * UPM
DOT_RISE = 0.02 * UPM
ALPHA_SCALE = 0.55


def glyphs(font, text, x, scale=1.0):
    cmap, gs, hmtx = font.getBestCmap(), font.getGlyphSet(), font['hmtx']
    out = []
    for ch in text:
        name = cmap[ord(ch)]
        pen = SVGPathPen(gs, ntos=lambda v: f'{v:.0f}')
        # y is flipped: font units go up, SVG goes down.
        gs[name].draw(TransformPen(pen, (scale, 0, 0, -scale, x, 0)))
        out.append(pen.getCommands())
        x += hmtx[name][0] * scale
    return ' '.join(out), x


a, x = glyphs(latin, 'slide', 0)
x += DOT_MARGIN
dot_x = x
x += DOT + DOT_MARGIN
b, x = glyphs(latin, 'community', x)
# The alpha sits at the top right, past the last letter.
x += 0.06 * UPM
c, end = glyphs(greek, 'α', x, ALPHA_SCALE)
w, h = round(end), ASC + DESC
rect = (f'<rect x="{dot_x:.0f}" y="{-(DOT - DOT_RISE):.0f}" width="{DOT:.0f}" '
        f'height="{DOT:.0f}" rx="{DOT * 0.18:.0f}" fill="var(--community-red)"/>')
# The alpha is red like the dot; its top is level with the letters' ascenders.
alpha_y = -ASC + 0.62 * UPM * ALPHA_SCALE
svg = (f'<svg class="wordmark" xmlns="http://www.w3.org/2000/svg" viewBox="0 {-ASC} {w} {h}" '
       f'aria-hidden="true" focusable="false"><path fill="currentColor" d="{a} {b}"/>{rect}'
       f'<path fill="var(--community-red)" transform="translate(0 {alpha_y:.0f})" d="{c}"/></svg>')
print('// Generated by scripts/generate-wordmark.py. Do not edit by hand.')
print(f'export const WORDMARK_SVG = {svg!r}')
print(f'export const WORDMARK_ASPECT = {w / h:.4f}')
